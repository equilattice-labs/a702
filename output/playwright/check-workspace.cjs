async (page) => {
  const results = [], errors = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(() => { window.__lcp = 0; new PerformanceObserver(list => { window.__lcp = list.getEntries().at(-1)?.startTime || 0; }).observe({type:'largest-contentful-paint',buffered:true}); });
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('heading', {name:'The mission board 4'}).waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert(await page.title() === 'Civiquill — Good questions. Public knowledge.', 'Civiquill page title');
  assert(await page.locator('.mission-row').count() === 4, 'Four clearly labeled sample briefs'); for (const b of await page.locator('.mission-row button[aria-pressed=true]').all()) await b.click();
  await page.getByRole('searchbox', {name:'Search missions'}).fill('liquidity');
  assert(await page.locator('.mission-row').count() === 1, 'Search narrows the mission list');
  await page.getByRole('searchbox', {name:'Search missions'}).fill('no-such-civiquill-question');
  await page.getByRole('heading', {name:'A fresh question might help.'}).waitFor();
  await page.getByRole('button', {name:'Explore all missions',exact:true}).click();
  assert(await page.locator('.mission-row').count() === 4, 'Empty search has working recovery');
  await page.locator('.filter-row').getByRole('button', {name:'Risk research',exact:true}).click();
  assert(await page.locator('.mission-row').count() === 1, 'Topic filter works');
  await page.locator('.filter-row').getByRole('button', {name:'All topics',exact:true}).click();
  await page.getByRole('combobox', {name:'Sort missions'}).selectOption('reward');
  assert((await page.locator('.mission-row').first().innerText()).includes('Where does liquidity'), 'Reward ordering works');
  await page.getByRole('combobox', {name:'Sort missions'}).selectOption('recommended');
  const firstBookmark = page.locator('.mission-row').first().getByRole('button', {name:/^(Save|Unsave) /});
  if (await firstBookmark.getAttribute('aria-pressed') === 'true') await firstBookmark.click();
  await firstBookmark.click();
  await page.reload();
  await page.getByRole('heading', {name:'The mission board 4'}).waitFor();
  await page.locator('.board-tabs').first().getByRole('button', {name:/^Saved/}).click();
  assert(await page.locator('.mission-row').count() === 1, 'Bookmark survives reload and saved view');
  await page.locator('.mission-row').first().getByRole('button', {name:/^Unsave /}).click();
  await page.getByRole('heading', {name:'Keep a question for later.'}).waitFor();
  await page.getByRole('button', {name:'Explore all missions',exact:true}).click();
  const briefButton=page.getByRole('button', {name:'What does a tokenized stock actually represent?',exact:true});
  await briefButton.click();
  const drawer=page.getByRole('dialog');
  await drawer.waitFor();
  assert(await drawer.getByText('This is a sample brief.',{exact:false}).isVisible(), 'Drawer distinguishes illustrative reward');
  await drawer.getByRole('button', {name:'Contribute',exact:true}).click();
  assert(await drawer.getByRole('button', {name:'Submit research',exact:true}).isDisabled(), 'Sample research submission disabled');
  assert(await drawer.getByRole('button', {name:'Fund this mission',exact:true}).isDisabled(), 'Sample funding disabled');
  await drawer.getByRole('button', {name:/^Review/}).click();
  await drawer.getByRole('heading', {name:'No research submitted yet.'}).waitFor();
  await drawer.getByRole('button', {name:'Brief',exact:true}).click();
  await page.screenshot({path:'output/playwright/civiquill-detail-desktop.png'});
  await page.keyboard.press('Escape');
  assert(await page.evaluate(() => document.activeElement?.textContent?.includes('What does a tokenized stock')), 'Escape restores focus to mission opener');
  await page.getByRole('button', {name:'Create mission',exact:true}).click();
  await drawer.getByLabel('What would you like to understand?').fill('How do settlement rights differ?');
  await drawer.getByLabel('Your working brief', {exact:false}).fill('Compare three primary sources. Explain rights, custody, and limitations.');
  await drawer.getByLabel('Public brief URL',{exact:true}).fill('javascript:alert(1)');
  await drawer.getByLabel('Reward pool · testnet ETH',{exact:true}).fill('0.000000000000000001');
  const future = new Date(Date.now()+86400000*7).toISOString().slice(0,16);
  await drawer.getByLabel('Deadline · your local time',{exact:true}).fill(future);
  await drawer.getByRole('button', {name:'Review your mission',exact:true}).click();
  assert(await drawer.getByRole('alert').isVisible(), 'Invalid public URL has visible validation');
  await drawer.getByLabel('Public brief URL',{exact:true}).fill('https://example.org/civiquill-brief');
  await drawer.getByRole('button', {name:'Review your mission',exact:true}).click();
  await drawer.getByRole('heading', {name:'How do settlement rights differ?'}).waitFor();
  assert((await drawer.innerText()).includes('0.000000000000000001 testnet ETH'), 'Review preserves exact 1 wei amount');
  await page.screenshot({path:'output/playwright/civiquill-create-review.png'});
  const downloaded=page.waitForEvent('download');
  await drawer.getByRole('button', {name:'Download brief',exact:true}).click();
  const file=await downloaded;
  assert(file.suggestedFilename()==='civiquill-research-brief.md','Download generates Civiquill brief file');
  await file.saveAs('output/playwright/civiquill-research-brief.md');
  await drawer.getByRole('button', {name:'Edit brief',exact:true}).click();
  assert(await drawer.getByLabel('What would you like to understand?').inputValue()==='How do settlement rights differ?','Review back navigation preserves draft');
  await page.keyboard.press('Escape');
  await page.getByRole('button', {name:'Connect wallet',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'No Ethereum wallet found.'}).waitFor();
  await page.getByRole('button', {name:'Dismiss wallet error'}).click();
  results.push('Missing wallet shows recoverable error');
  await page.getByRole('button', {name:'Contributor guide',exact:true}).click();
  await drawer.waitFor();
  for(let i=0;i<8;i++) {await page.keyboard.press('Tab');assert(await page.evaluate(()=>!!document.activeElement?.closest('dialog')),'Dialog keyboard focus remains contained '+i);}
  await page.keyboard.press('Escape');
  await page.getByRole('button', {name:'Back to top ↑',exact:true}).click();
  await page.screenshot({path:'output/playwright/civiquill-desktop.png',fullPage:true});
  await page.screenshot({path:'output/playwright/civiquill-desktop-viewport.png'});
  await page.addScriptTag({path:'output/playwright/axe.min.js'});
  const accessibility=await page.evaluate(async()=>{const result=await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return result.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));});
  const metrics=await page.evaluate(()=>({lcp:window.__lcp,paint:performance.getEntriesByType('paint').map(x=>({name:x.name,ms:x.startTime})),overflow:document.documentElement.scrollWidth>innerWidth,fonts:[...document.fonts].map(f=>({family:f.family,status:f.status})),resources:performance.getEntriesByType('resource').filter(x=>!x.name.includes('axe.min.js')).map(x=>({url:x.name,bytes:x.transferSize}))}));
  assert(!metrics.overflow,'Desktop has no horizontal overflow');
  assert(errors.length===0,'No uncaught browser errors');
  return {results,accessibility,metrics,errors};
}
