async (page) => {
  const results=[],accessibility=[],layouts=[];
  const assert=(ok,message)=>{if(!ok)throw new Error(message);results.push(message);};
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('heading',{name:'The mission board 4'}).waitFor();
  await page.evaluate(()=>document.fonts.ready);
  assert(await page.locator('.sidebar').isHidden(),'Mobile navigation is hidden until opened');
  await page.getByRole('button',{name:'Toggle navigation',exact:true}).click();
  await page.locator('.sidebar').waitFor({state:'visible'}); assert(await page.locator('.sidebar').isVisible(),'Mobile navigation opens');
  assert(await page.locator('.workspace').getAttribute('inert')!==null,'Page is inert while navigation is open');
  await page.keyboard.press('Shift+Tab');
  assert(await page.evaluate(()=>!!document.activeElement.closest('.sidebar')),'Navigation reverse Tab remains contained');
  await page.keyboard.press('Escape');
  assert(await page.locator('.sidebar').isHidden(),'Escape closes mobile navigation');
  assert(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')==='Toggle navigation'),'Mobile menu restores opener focus');
  await page.getByRole('button',{name:'Find your next mission',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search missions'}).fill('liquidity');
  assert(await page.locator('.mission-row').count()===1,'Mobile search works');
  await page.getByRole('searchbox',{name:'Search missions'}).fill('');
  await page.locator('.filter-row').getByRole('button',{name:'Ecosystem',exact:true}).click();
  assert(await page.locator('.mission-row').count()===1,'Mobile category filter works');
  const savedButton=page.locator('.mission-row').getByRole('button',{name:/^(Save|Unsave) /}); if(await savedButton.getAttribute('aria-pressed')==='true') await savedButton.click(); await savedButton.click();
  await page.locator('.board-tabs').first().getByRole('button',{name:/^Saved/}).click();
  assert(await page.locator('.mission-row').count()===1,'Mobile save and saved list work');
  await page.getByRole('button',{name:'A field guide to the Robinhood Chain ecosystem',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  assert(!(await page.evaluate(()=>document.querySelector('dialog').scrollWidth>document.querySelector('dialog').clientWidth)),'Mobile drawer has no horizontal overflow');
  await page.addScriptTag({path:'output/playwright/axe.min.js'});
  const axe=async(label)=>{const violations=await page.evaluate(async()=>{const r=await window.axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}});return r.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));});accessibility.push({label,violations});};
  await axe('mobile-drawer');
  await page.screenshot({path:'output/playwright/civiquill-detail-mobile.png'});
  await page.getByRole('dialog').getByRole('button',{name:'Contribute',exact:true}).click();
  assert(await page.getByRole('button',{name:'Submit research',exact:true}).isDisabled(),'Mobile sample transaction controls are disabled');
  await page.keyboard.press('Escape');
  await page.locator('.board-tabs').first().getByRole('button',{name:'All missions',exact:true}).click();
  await page.locator('.filter-row').getByRole('button',{name:'All topics',exact:true}).click();
  await page.getByRole('button',{name:'Create mission',exact:true}).click();
  await page.getByLabel('What would you like to understand?').fill('A question drafted on mobile');
  await page.getByLabel('Public brief URL',{exact:true}).fill('https://example.org/mobile-brief');
  await page.getByLabel('Reward pool · testnet ETH',{exact:true}).fill('0.05');
  await page.getByLabel('Deadline · your local time',{exact:true}).fill(new Date(Date.now()+86400000*7).toISOString().slice(0,16));
  await page.getByRole('button',{name:'Review your mission',exact:true}).click();
  await page.getByRole('heading',{name:'A question drafted on mobile'}).waitFor();
  await page.screenshot({path:'output/playwright/civiquill-create-mobile.png'});
  await axe('mobile-create-review');
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download brief',exact:true}).click();
  assert((await download).suggestedFilename()==='civiquill-research-brief.md','Mobile draft download works');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Toggle navigation',exact:true}).click();
  await page.getByRole('button',{name:'Your rewards',exact:true}).click();
  await page.getByRole('heading',{name:'Connect to see your rewards.'}).waitFor();
  await page.getByRole('dialog').getByRole('button',{name:'Connect wallet',exact:true}).click();
  await page.getByRole('dialog').getByRole('alert').waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Dismiss wallet error'}).click();
  results.push('Mobile rewards and missing-wallet feedback work');
  await page.getByRole('button',{name:'Back to top ↑',exact:true}).click();
  for(const [width,height] of [[320,740],[390,844],[768,1024],[1024,900],[1440,1000],[1920,1080]]) {
    await page.setViewportSize({width,height});
    await page.evaluate(()=>window.scrollTo(0,0));
    const layout=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,overflow:document.documentElement.scrollWidth>innerWidth,header:document.querySelector('.topbar').getBoundingClientRect().width,fonts:[...document.fonts].map(f=>f.status)}));
    layouts.push(layout); assert(!layout.overflow,`No page overflow at ${width}px`);
    if([390,768,1440].includes(width)){await axe(`${width}px-page`);await page.screenshot({path:`output/playwright/civiquill-${width}.png`,fullPage:true});await page.screenshot({path:`output/playwright/civiquill-${width}-viewport.png`});}
  }
  await page.setViewportSize({width:640,height:900});
  await page.emulateMedia({forcedColors:'active',reducedMotion:'reduce'});
  assert(await page.getByRole('button',{name:'Create mission',exact:true}).isVisible(),'Forced-color mode keeps primary action visible');
  await page.emulateMedia({forcedColors:'none',reducedMotion:'no-preference'});
  return {results,layouts,accessibility};
}
